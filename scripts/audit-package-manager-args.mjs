/**
 * GB Coder — Package Manager Command & Arguments Verification Suite
 *
 * Verifies that package managers (npm, Yarn Classic, Yarn 4 / Berry, pnpm)
 * receive only their supported arguments, that Yarn 4 never receives --no-audit,
 * that Yarn Berry Plug'n'Play vs nodeLinker compatibility is correctly reported,
 * and that framework entry points and Vite plugins are safely generated.
 */

import { test, describe, after } from 'node:test';
import assert from 'node:assert/strict';
import { services, cleanup } from './audit-harness.mjs';

const {
  detectProjectCommands,
  getPackageManagerInstallArgs,
  filesToFileSystemTree,
} = services;

after(() => cleanup());

describe('Package Manager Install Arguments', () => {
  test('npm install arguments include isolated cache and --no-audit', () => {
    const args = getPackageManagerInstallArgs('npm');
    assert.deepStrictEqual(args, ['install', '--prefer-offline', '--no-audit', '--cache', '/tmp/.npm-cache']);
  });

  test('Yarn Classic (v1) install arguments use --cache-folder and never --no-audit', () => {
    const args = getPackageManagerInstallArgs('yarn', '1.22.22');
    assert.ok(args.includes('install'));
    assert.ok(args.includes('--prefer-offline'));
    assert.ok(args.includes('--cache-folder'));
    assert.ok(!args.includes('--no-audit'), 'Yarn Classic must never receive npm --no-audit');
    assert.ok(!args.includes('--cache'), 'Yarn Classic must use --cache-folder, not npm --cache');
  });

  test('Yarn 4 / Berry install arguments are strictly clean and NEVER include --no-audit or --prefer-offline', () => {
    const args = getPackageManagerInstallArgs('yarn', '4.1.0');
    assert.deepStrictEqual(args, ['install'], 'Yarn 4 install must only pass supported arguments');
    assert.ok(!args.includes('--no-audit'), 'CRITICAL: Yarn 4 rejects --no-audit');
    assert.ok(!args.includes('--prefer-offline'), 'Yarn 4 rejects --prefer-offline');
    assert.ok(!args.includes('--cache'), 'Yarn 4 rejects --cache');
  });

  test('pnpm install arguments use --prefer-offline and never --no-audit or npm --cache', () => {
    const args = getPackageManagerInstallArgs('pnpm');
    assert.deepStrictEqual(args, ['install', '--prefer-offline']);
    assert.ok(!args.includes('--no-audit'));
    assert.ok(!args.includes('--cache'));
  });
});

describe('Package Manager Detection from Manifest & Lockfiles', () => {
  test('packageManager field specifies Yarn 4 with precedence over lockfile', () => {
    const files = [
      {
        path: 'package.json',
        content: JSON.stringify({
          name: 'yarn-4-app',
          packageManager: 'yarn@4.2.2',
          scripts: { dev: 'vite' },
        }),
      },
      { path: 'package-lock.json', content: '{}' },
    ];
    const info = detectProjectCommands(files);
    assert.strictEqual(info.packageManager, 'yarn');
    assert.strictEqual(info.packageManagerVersion, '4.2.2');
    assert.deepStrictEqual(info.installArgs, ['install']);
    assert.ok(!info.installArgs.includes('--no-audit'));
  });

  test('packageManager field specifies pnpm', () => {
    const files = [
      {
        path: 'package.json',
        content: JSON.stringify({
          name: 'pnpm-app',
          packageManager: 'pnpm@8.15.0',
          scripts: { dev: 'next dev' },
        }),
      },
    ];
    const info = detectProjectCommands(files);
    assert.strictEqual(info.packageManager, 'pnpm');
    assert.deepStrictEqual(info.installArgs, ['install', '--prefer-offline']);
  });

  test('Yarn lockfile detection when packageManager field is absent', () => {
    const files = [
      {
        path: 'package.json',
        content: JSON.stringify({
          name: 'classic-yarn-app',
          scripts: { dev: 'vite' },
        }),
      },
      {
        path: 'yarn.lock',
        content: '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n',
      },
    ];
    const info = detectProjectCommands(files);
    assert.strictEqual(info.packageManager, 'yarn');
    assert.strictEqual(info.packageManagerSource, 'lockfile');
    assert.deepStrictEqual(info.installArgs, ['install', '--prefer-offline', '--cache-folder', '/tmp/.yarn-cache']);
  });

  test('Yarn Berry lockfile detection via __metadata v6', () => {
    const files = [
      {
        path: 'package.json',
        content: JSON.stringify({
          name: 'berry-yarn-app',
          scripts: { dev: 'vite' },
        }),
      },
      {
        path: 'yarn.lock',
        content: '__metadata:\n  version: 6\n  cacheKey: 8\n',
      },
      {
        path: '.yarnrc.yml',
        content: 'nodeLinker: "node-modules"\n',
      },
    ];
    const info = detectProjectCommands(files);
    assert.strictEqual(info.packageManager, 'yarn');
    assert.deepStrictEqual(info.installArgs, ['install']);
    assert.strictEqual(info.compatibilityStatus, 'fully_supported');
  });
});

describe('Yarn Berry Compatibility & nodeLinker Detection', () => {
  test('Yarn Berry without nodeLinker defaults to unsupported_version (Plug\'n\'Play)', () => {
    const files = [
      {
        path: 'package.json',
        content: JSON.stringify({
          name: 'yarn-berry-pnp',
          packageManager: 'yarn@4.0.0',
          scripts: { dev: 'vite' },
        }),
      },
    ];
    const info = detectProjectCommands(files);
    assert.strictEqual(info.compatibilityStatus, 'unsupported_version');
    assert.strictEqual(info.runtimeAvailability, 'fallback_required');
    assert.ok(info.runtimeWarning?.includes('node-modules linker'));
  });

  test('Yarn Berry WITH nodeLinker: node-modules in .yarnrc.yml is fully supported', () => {
    const files = [
      {
        path: 'package.json',
        content: JSON.stringify({
          name: 'yarn-berry-node-modules',
          packageManager: 'yarn@4.0.0',
          scripts: { dev: 'vite' },
        }),
      },
      {
        path: '.yarnrc.yml',
        content: 'nodeLinker: node-modules\n',
      },
    ];
    const info = detectProjectCommands(files);
    assert.strictEqual(info.compatibilityStatus, 'fully_supported');
    assert.strictEqual(info.runtimeAvailability, 'native');
    assert.strictEqual(info.runtimeWarning, null);
    assert.deepStrictEqual(info.installArgs, ['install']);
  });
});

describe('Framework FileSystemTree Entry & Vite Plugin Fallback', () => {
  test('React without main/index creates bootstrapped main.jsx and index.html', () => {
    const files = [
      {
        path: 'src/App.jsx',
        content: 'export default function App() { return <h1>Hello</h1>; }',
      },
      {
        path: 'package.json',
        content: JSON.stringify({
          dependencies: { react: '^18.0.0', 'react-dom': '^18.0.0' },
        }),
      },
    ];
    const tree = filesToFileSystemTree(files);
    assert.ok(tree['index.html'] && 'file' in tree['index.html']);
    const indexHtml = tree['index.html'].file.contents;
    assert.ok(indexHtml.includes('/main.jsx'), 'index.html must reference bootstrapped main.jsx');
    assert.ok(tree['main.jsx'] && 'file' in tree['main.jsx'], 'main.jsx bootstrap must be created');
    assert.ok(tree['main.jsx'].file.contents.includes('ReactDOM.createRoot'));
  });

  test('React without @vitejs/plugin-react in manifest does not inject broken plugin import', () => {
    const files = [
      {
        path: 'App.jsx',
        content: 'export default function App() { return <h1>Hello</h1>; }',
      },
      {
        path: 'package.json',
        content: JSON.stringify({
          dependencies: { react: '^18.0.0' },
        }),
      },
    ];
    const tree = filesToFileSystemTree(files);
    assert.ok(tree['vite.config.js'] && 'file' in tree['vite.config.js']);
    const viteConfig = tree['vite.config.js'].file.contents;
    assert.ok(!viteConfig.includes('@vitejs/plugin-react'), 'Must not import uninstalled plugin');
    assert.ok(viteConfig.includes('export default defineConfig'));
  });

  test('React WITH @vitejs/plugin-react in manifest DOES inject plugin', () => {
    const files = [
      {
        path: 'App.jsx',
        content: 'export default function App() { return <h1>Hello</h1>; }',
      },
      {
        path: 'package.json',
        content: JSON.stringify({
          devDependencies: { '@vitejs/plugin-react': '^4.0.0', vite: '^5.0.0' },
        }),
      },
    ];
    const tree = filesToFileSystemTree(files);
    assert.ok(tree['vite.config.js'] && 'file' in tree['vite.config.js']);
    const viteConfig = tree['vite.config.js'].file.contents;
    assert.ok(viteConfig.includes('@vitejs/plugin-react'), 'Must import installed plugin');
    assert.ok(viteConfig.includes('plugins: [react()]'));
  });
});
