import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function packStatusDocuments(dist) {
  const templates = resolve(dist, '_status-documents');
  const pages = {};
  for (const name of readdirSync(templates)) {
    if (!/^[45]\d{2}$/.test(name)) throw new Error('Invalid error document filename');
    pages[name] = readFileSync(join(templates, name, 'index.html'), 'utf8');
  }
  if (!pages[404] || !pages[500]) throw new Error('Status document build is incomplete');
  const output = join(root, 'api', '_lib', 'status-pages.generated.cjs');
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, `// Generated by Astro; do not edit.\nmodule.exports = ${JSON.stringify(pages)};\n`);
  // The checked path is a direct child of the explicit build directory.
  if (dirname(templates) !== resolve(dist) || !existsSync(templates)) throw new Error('Unsafe status document cleanup target');
  rmSync(templates, { recursive: true });
  console.log(`[status] Packed ${Object.keys(pages).length} error documents; removed public templates.`);
}
